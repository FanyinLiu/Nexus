/**
 * Suppression fingerprints for memories the user deleted one by one.
 *
 * A delete writes only a salted 64-bit fingerprint of the normalized wording,
 * never the wording itself. Matching is exact after trim / whitespace collapse /
 * lowercase / trailing-punctuation removal; no fuzzy or semantic matching is
 * attempted.
 *
 * The fingerprint is synchronous because the extract / plan / reconcile paths
 * are synchronous and Web Crypto's digest is async-only. Two seeded 32-bit
 * FNV-1a passes are concatenated, and a per-install salt is mixed into the
 * input so the same wording does not hash the same on another install.
 *
 * v1 (`v1:…`) and the unreleased `v2:` SHA-256 hex form are dropped on read:
 * neither shipped, and only the hash was stored, so they cannot be rehashed.
 */

/** Keep the newest tombstones only; older facts may be extracted again. */
export const FORGOTTEN_MEMORY_LIMIT = 500

/** 64 bits (two seeded 32-bit passes), hex-encoded, under the current format. */
const FINGERPRINT_PATTERN = /^v2:[0-9a-f]{16}$/
const SALT_PATTERN = /^[0-9a-f]{32}$/
const FNV_PRIME = 0x01000193
const FIRST_SEED = 0x811c9dc5
const SECOND_SEED = 0x9e3779b9

/** Case, whitespace, and trailing punctuation are not part of the identity. */
export function normalizeForgottenMemoryText(content: string): string {
  return content
    .replace(/\s+/gu, ' ')
    .trim()
    .toLowerCase()
    .replace(/[\p{P}]+$/gu, '')
    .trim()
}

/** True when a per-install salt generated by the storage layer is well formed. */
export function isValidForgottenMemorySalt(value: unknown): value is string {
  return typeof value === 'string' && SALT_PATTERN.test(value)
}

function fnv1a32(value: string, seed: number): number {
  let hash = seed >>> 0
  for (let index = 0; index < value.length; index += 1) {
    hash ^= value.charCodeAt(index)
    hash = Math.imul(hash, FNV_PRIME) >>> 0
  }
  return hash >>> 0
}

/** Salt is mixed into the input so fingerprints are install-specific. */
function saltedFingerprintHex(salt: string, normalized: string): string {
  const input = `${salt}\u0000${normalized}`
  const first = fnv1a32(input, FIRST_SEED)
  const second = fnv1a32(input, SECOND_SEED)
  return `${first.toString(16).padStart(8, '0')}${second.toString(16).padStart(8, '0')}`
}

/**
 * Empty text or a missing/invalid salt returns an empty fingerprint so it is
 * never stored or matched.
 */
export function fingerprintForgottenMemoryText(content: string, salt: string): string {
  if (!isValidForgottenMemorySalt(salt)) return ''
  const normalized = normalizeForgottenMemoryText(content)
  if (!normalized) return ''
  return `v2:${saltedFingerprintHex(salt, normalized)}`
}

/** True when the exact normalized text is in the suppression list. */
export function isForgottenMemoryText(
  content: string,
  fingerprints: readonly string[] | undefined,
  salt: string,
): boolean {
  if (!fingerprints?.length) return false
  const fingerprint = fingerprintForgottenMemoryText(content, salt)
  return Boolean(fingerprint) && fingerprints.includes(fingerprint)
}

/** Add or refresh one tombstone, returning a new capped list. */
export function addForgottenMemoryFingerprint(
  fingerprints: readonly string[],
  content: string,
  salt: string,
): string[] {
  const fingerprint = fingerprintForgottenMemoryText(content, salt)
  if (!fingerprint) return [...fingerprints]
  return [
    fingerprint,
    ...fingerprints.filter((entry) => entry !== fingerprint),
  ].slice(0, FORGOTTEN_MEMORY_LIMIT)
}

/** Drop one tombstone, e.g. after the user manually adds the fact again. */
export function removeForgottenMemoryFingerprint(
  fingerprints: readonly string[],
  content: string,
  salt: string,
): string[] {
  const fingerprint = fingerprintForgottenMemoryText(content, salt)
  if (!fingerprint) return [...fingerprints]
  return fingerprints.filter((entry) => entry !== fingerprint)
}

/** Tolerate corrupt blobs and duplicate rows; keep only well-formed entries. */
export function parseForgottenMemoryFingerprints(raw: unknown): string[] {
  if (!Array.isArray(raw)) return []
  const seen = new Set<string>()
  const fingerprints: string[] = []
  for (const item of raw) {
    if (typeof item !== 'string' || !FINGERPRINT_PATTERN.test(item)) continue
    if (seen.has(item)) continue
    seen.add(item)
    fingerprints.push(item)
    if (fingerprints.length >= FORGOTTEN_MEMORY_LIMIT) break
  }
  return fingerprints
}
