#!/usr/bin/env node

/**
 * Generates the renderer-facing desktopPet bridge surface from the untyped
 * CommonJS preload, plus per-method argument/result types derived from the
 * main-process IPC schema validators and handler return values.
 *
 * Arguments come from the schema validator that guards each channel; results
 * come from a type-checked handler callback. Anything not statically
 * determinable stays `unknown` so the generated surface never guesses.
 *
 * Run with no arguments to write the file, or `--check` to assert the checked-in
 * copy is fresh. The pure extract/render helpers are exported for tests.
 */

import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
// TypeScript 7 removed the classic compiler API from the main export.
// Audit tooling keeps using the TS 6 API via the typescript6 alias.
import ts from 'typescript6'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const IPC_DIR = join(ROOT, 'electron', 'ipc')
const PRELOAD_PATH = join(ROOT, 'electron', 'preload.js')
const GENERATED_PATH = join(ROOT, 'src', 'types', 'generated', 'desktopPetBridge.generated.ts')
const BRIDGE_NAME = 'desktopPet'
const CHECK_FLAG = '--check'
const STALE_MESSAGE = 'desktopPet bridge types are stale; run npm run ipc:types:generate'
const UNKNOWN_TYPE = 'unknown'

const HEADER = '// Generated by scripts/generate-ipc-types.mjs from electron/preload.js. Do not edit by hand. Run `npm run ipc:types:generate`.'

const SAFE_NAMED_TYPES = new Set([
  'Array',
  'ReadonlyArray',
  'Record',
  'Date',
  'Float32Array',
  'Int32Array',
  'Map',
  'Set',
  'Promise',
])

function parseSource(fileName, source) {
  return ts.createSourceFile(fileName, source, ts.ScriptTarget.Latest, true, ts.ScriptKind.JS)
}

function unwrapExpression(node) {
  let current = node
  while (
    ts.isParenthesizedExpression(current)
    || ts.isAsExpression(current)
    || ts.isSatisfiesExpression(current)
    || ts.isNonNullExpression(current)
  ) {
    current = current.expression
  }
  return current
}

function isStringLiteralLike(node) {
  return ts.isStringLiteral(node) || ts.isNoSubstitutionTemplateLiteral(node)
}

function literalText(node) {
  return isStringLiteralLike(node) ? node.text : null
}

function staticPropertyName(node) {
  const name = node.name
  if (!name) return null
  if (ts.isIdentifier(name) || isStringLiteralLike(name) || ts.isNumericLiteral(name)) {
    return name.text
  }
  return null
}

function findBridgeObject(sourceFile) {
  let result = null

  function visit(node) {
    if (
      ts.isCallExpression(node)
      && ts.isPropertyAccessExpression(node.expression)
      && node.expression.name.text === 'exposeInMainWorld'
    ) {
      const [nameArg, apiArg] = node.arguments
      if (nameArg && literalText(nameArg) === BRIDGE_NAME) {
        if (result) {
          throw new Error(`electron/preload.js exposes '${BRIDGE_NAME}' more than once; expected exactly one call`)
        }
        if (!apiArg) {
          throw new Error(`contextBridge.exposeInMainWorld('${BRIDGE_NAME}', ...) has no bridge object argument`)
        }
        const apiObject = unwrapExpression(apiArg)
        if (!ts.isObjectLiteralExpression(apiObject)) {
          throw new Error(`contextBridge.exposeInMainWorld('${BRIDGE_NAME}', ...) must be passed an object literal`)
        }
        result = apiObject
      }
    }
    ts.forEachChild(node, visit)
  }

  visit(sourceFile)
  if (!result) {
    throw new Error(`electron/preload.js has no contextBridge.exposeInMainWorld('${BRIDGE_NAME}', ...) call`)
  }
  return result
}

function isIpcCall(node, methodName, sourceFile) {
  return (
    ts.isCallExpression(node)
    && ts.isPropertyAccessExpression(node.expression)
    && node.expression.name.text === methodName
    && node.expression.expression.getText(sourceFile) === 'ipcRenderer'
  )
}

function isDirectReturnExpression(node) {
  let current = node
  let parent = current.parent
  while (
    parent
    && (ts.isParenthesizedExpression(parent) || ts.isAsExpression(parent) || ts.isSatisfiesExpression(parent))
  ) {
    current = parent
    parent = parent.parent
  }
  if (!parent) return false
  if (ts.isArrowFunction(parent)) return parent.body === current
  return ts.isReturnStatement(parent)
}

function parameterNames(node) {
  if (ts.isPropertyAssignment(node)) {
    const value = unwrapExpression(node.initializer)
    if (ts.isArrowFunction(value) || ts.isFunctionExpression(value)) {
      return value.parameters
        .map((parameter) => (ts.isIdentifier(parameter.name) ? parameter.name.text : null))
        .filter((name) => name !== null)
    }
    return []
  }
  if (ts.isMethodDeclaration(node)) {
    return node.parameters
      .map((parameter) => (ts.isIdentifier(parameter.name) ? parameter.name.text : null))
      .filter((name) => name !== null)
  }
  return []
}

function collectChannels(valueNode, sourceFile, entry) {
  function firstArgumentChannel(node) {
    const first = node.arguments[0]
    return first ? literalText(first) : null
  }

  function visit(node) {
    if (isIpcCall(node, 'invoke', sourceFile)) {
      const channel = firstArgumentChannel(node)
      if (channel === null) {
        throw new Error(`ipcRenderer.invoke call inside desktopPet.${entry.name} must use a string literal channel`)
      }
      const payloadArg = node.arguments[1]
      entry.invoke.push(channel)
      entry.calls.push({
        channel,
        direct: isDirectReturnExpression(node),
        payloadExpression: payloadArg ? payloadArg.getText(sourceFile) : null,
        argumentCount: node.arguments.length,
      })
    } else if (isIpcCall(node, 'on', sourceFile)) {
      const channel = firstArgumentChannel(node)
      if (channel === null) {
        throw new Error(`ipcRenderer.on call inside desktopPet.${entry.name} must use a string literal channel`)
      }
      entry.events.push(channel)
    }
    ts.forEachChild(node, visit)
  }

  visit(valueNode)
}

function mergeEntry(surface, name, conditional) {
  const existing = surface[name]
  if (existing) {
    existing.conditional = existing.conditional || conditional
    return existing
  }
  const entry = { name, conditional, invoke: [], events: [], params: [], calls: [] }
  surface[name] = entry
  return entry
}

function collectMembers(properties, conditional, surface, sourceFile) {
  for (const member of properties) {
    if (ts.isSpreadAssignment(member)) {
      const spread = unwrapExpression(member.expression)
      if (!ts.isConditionalExpression(spread)) {
        throw new Error('desktopPet bridge spreads are only supported as conditional spreads (`...(cond ? { ... } : {})`)')
      }
      for (const branch of [spread.whenTrue, spread.whenFalse]) {
        const branchObject = unwrapExpression(branch)
        if (!ts.isObjectLiteralExpression(branchObject)) {
          throw new Error('desktopPet conditional spread branches must both be object literals')
        }
        collectMembers(branchObject.properties, true, surface, sourceFile)
      }
      continue
    }

    if (
      !ts.isPropertyAssignment(member)
      && !ts.isShorthandPropertyAssignment(member)
      && !ts.isMethodDeclaration(member)
    ) {
      throw new Error(`unsupported desktopPet bridge property kind: ${ts.SyntaxKind[member.kind]}`)
    }

    const name = staticPropertyName(member)
    if (name === null) {
      throw new Error('desktopPet bridge property names must be static identifiers or string literals')
    }

    const entry = mergeEntry(surface, name, conditional)
    entry.params = parameterNames(member)
    if (ts.isPropertyAssignment(member)) {
      collectChannels(member.initializer, sourceFile, entry)
    } else if (ts.isMethodDeclaration(member)) {
      collectChannels(member, sourceFile, entry)
    }
  }
}

/**
 * Extract the desktopPet bridge surface from preload source text.
 *
 * @param {string} source electron/preload.js contents
 * @returns {Record<string, {
 *   conditional: boolean,
 *   invoke: string[],
 *   events: string[],
 *   params: string[],
 *   calls: Array<{ channel: string, direct: boolean, payloadExpression: string | null, argumentCount: number }>,
 * }>}
 */
export function extractDesktopPetBridgeSurface(source) {
  const sourceFile = parseSource('electron/preload.js', source)
  const bridgeObject = findBridgeObject(sourceFile)
  const surface = {}
  collectMembers(bridgeObject.properties, false, surface, sourceFile)

  const normalized = {}
  for (const name of Object.keys(surface).sort()) {
    const entry = surface[name]
    normalized[name] = {
      conditional: entry.conditional,
      invoke: [...new Set(entry.invoke)].sort(),
      events: [...new Set(entry.events)].sort(),
      params: [...entry.params],
      calls: [...entry.calls].sort((a, b) => (
        a.channel.localeCompare(b.channel)
        || (a.payloadExpression ?? '').localeCompare(b.payloadExpression ?? '')
      )),
    }
  }
  return normalized
}

function quote(value) {
  return `'${String(value).replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`
}

function propertyKey(name) {
  return /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(name) ? name : quote(name)
}

function isIdentifierName(name) {
  return /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(name)
}

function renderUnion(typeName, values) {
  if (values.length === 0) return `export type ${typeName} = never`
  if (values.length === 1) return `export type ${typeName} = ${quote(values[0])}`
  return [
    `export type ${typeName} =`,
    ...values.map((value) => `  | ${quote(value)}`),
  ].join('\n')
}

function renderEnumLiteral(value) {
  return typeof value === 'string' ? quote(value) : String(value)
}

function hasCallSignature(checker, type) {
  return checker.getSignaturesOfType(type, ts.SignatureKind.Call).length > 0
}

function renderType(checker, type, seen, fallbackNode) {
  if (!type) return UNKNOWN_TYPE
  if (seen.has(type)) return UNKNOWN_TYPE

  const flags = type.flags
  if (flags & ts.TypeFlags.Any) return 'any'
  if (flags & ts.TypeFlags.Unknown) return UNKNOWN_TYPE
  if (flags & ts.TypeFlags.Never) return 'never'
  if (flags & ts.TypeFlags.Void) return 'void'
  if (flags & ts.TypeFlags.Null) return 'null'
  if (flags & ts.TypeFlags.Undefined) return 'undefined'
  if (flags & ts.TypeFlags.StringLiteral) return renderEnumLiteral(type.value)
  if (flags & ts.TypeFlags.NumberLiteral) return String(type.value)
  if (flags & ts.TypeFlags.BooleanLiteral) return type.intrinsicName
  if (flags & ts.TypeFlags.String) return 'string'
  if (flags & ts.TypeFlags.Number) return 'number'
  if (flags & ts.TypeFlags.Boolean) return 'boolean'
  if (flags & ts.TypeFlags.BigInt) return 'bigint'
  if (flags & ts.TypeFlags.ESSymbol) return 'symbol'
  if (flags & ts.TypeFlags.NonPrimitive) return 'object'
  if (flags & ts.TypeFlags.TypeParameter) return UNKNOWN_TYPE

  if (type.isUnion && type.isUnion()) {
    const parts = []
    for (const member of type.types) {
      const rendered = renderType(checker, member, seen, fallbackNode)
      if (!parts.includes(rendered)) parts.push(rendered)
    }
    if (parts.includes('true') && parts.includes('false')) {
      const withoutBooleans = parts.filter((part) => part !== 'true' && part !== 'false')
      withoutBooleans.push('boolean')
      return withoutBooleans.length === 1 ? 'boolean' : withoutBooleans.join(' | ')
    }
    return parts.length === 1 ? parts[0] : parts.join(' | ')
  }
  if (type.isIntersection && type.isIntersection()) {
    return type.types.map((member) => renderType(checker, member, seen, fallbackNode)).join(' & ')
  }

  const symbolName = type.symbol && type.symbol.name
  if (symbolName && SAFE_NAMED_TYPES.has(symbolName)) {
    const typeArguments = checker.getTypeArguments(type)
    if (typeArguments.length > 0) {
      return `${symbolName}<${typeArguments.map((argument) => renderType(checker, argument, seen, fallbackNode)).join(', ')}>`
    }
    return symbolName
  }

  if (checker.isTupleType(type)) {
    const typeArguments = checker.getTypeArguments(type)
    const elementFlags = type.target.elementFlags ?? []
    return `[${typeArguments.map((argument, index) => (
      elementFlags[index] & ts.ElementFlags.Optional
        ? `${renderType(checker, argument, seen, fallbackNode)}?`
        : renderType(checker, argument, seen, fallbackNode)
    )).join(', ')}]`
  }

  if (checker.isArrayType(type)) {
    const typeArguments = checker.getTypeArguments(type)
    return `${typeArguments.map((argument) => renderType(checker, argument, seen, fallbackNode)).join(' | ')}[]`
  }
  if (checker.isArrayLikeType(type)) {
    const typeArguments = checker.getTypeArguments(type)
    return `Array<${typeArguments.map((argument) => renderType(checker, argument, seen, fallbackNode)).join(' | ')}>`
  }

  const properties = checker.getPropertiesOfType(type)
  const stringIndex = checker.getIndexInfoOfType(type, ts.IndexKind.String)
  const numberIndex = checker.getIndexInfoOfType(type, ts.IndexKind.Number)
  if (properties.length === 0 && !stringIndex && !numberIndex) {
    if (hasCallSignature(checker, type)) return '(...args: unknown[]) => unknown'
    return '{}'
  }
  if (properties.length === 0 && stringIndex && !numberIndex) {
    return `Record<string, ${renderType(checker, stringIndex.type, seen, fallbackNode)}>`
  }
  if (properties.length === 0 && numberIndex && !stringIndex) {
    return `Record<number, ${renderType(checker, numberIndex.type, seen, fallbackNode)}>`
  }

  const nextSeen = new Set(seen)
  nextSeen.add(type)
  const members = []
  const declarationFallback = fallbackNode ?? type.symbol?.declarations?.[0]
  for (const property of properties) {
    const declaration = property.declarations?.[0] ?? property.valueDeclaration ?? declarationFallback
    const propertyType = checker.getTypeOfSymbolAtLocation(property, declaration)
    const optional = Boolean(property.flags & ts.SymbolFlags.Optional)
    let rendered = renderType(checker, propertyType, nextSeen, declarationFallback)
    if (optional) {
      const parts = rendered.split(' | ')
      const undefinedIndex = parts.indexOf('undefined')
      if (undefinedIndex >= 0) parts.splice(undefinedIndex, 1)
      rendered = parts.join(' | ') || 'undefined'
    }
    const name = isIdentifierName(property.name) ? property.name : quote(property.name)
    members.push(`${name}${optional ? '?' : ''}: ${rendered}`)
  }
  if (stringIndex) members.push(`[key: string]: ${renderType(checker, stringIndex.type, nextSeen, fallbackNode)}`)
  if (numberIndex) members.push(`[key: number]: ${renderType(checker, numberIndex.type, nextSeen, fallbackNode)}`)
  return `{ ${members.join('; ')} }`
}

function isUsableArgumentType(text) {
  if (!text || text === UNKNOWN_TYPE || text === 'any' || text === 'object' || text === '{}') return false
  if (/[{}]\s*[{}]/.test(text)) return false
  if (/\b(any|unknown|object)\b/.test(text)) return false
  return true
}

function isUsableResultType(text) {
  if (!text || text === UNKNOWN_TYPE || text === 'any' || text === 'object' || text === '{}') return false
  if (/\b(any|unknown|object)\b/.test(text)) return false
  if (text.includes('=>')) return false
  return true
}

function findVariableInitializer(sourceFile, name) {
  let found = null
  function visit(node) {
    if (found) return
    if (ts.isVariableStatement(node)) {
      for (const declaration of node.declarationList.declarations) {
        if (ts.isIdentifier(declaration.name) && declaration.name.text === name && declaration.initializer) {
          found = unwrapExpression(declaration.initializer)
          return
        }
      }
    }
    ts.forEachChild(node, visit)
  }
  visit(sourceFile)
  return found
}

function schemaAllowsMissingPayload(validatorDeclaration) {
  const sourceFile = validatorDeclaration.getSourceFile()
  let allowsMissing = false
  function visit(node) {
    if (allowsMissing) return
    if (
      ts.isCallExpression(node)
      && ts.isIdentifier(node.expression)
      && node.expression.text === 'validateIpcPayload'
    ) {
      const schemaNode = node.arguments[2] ? unwrapExpression(node.arguments[2]) : null
      if (!schemaNode) return
      const schemaObject = ts.isIdentifier(schemaNode)
        ? findVariableInitializer(sourceFile, schemaNode.text)
        : schemaNode
      if (!schemaObject || !ts.isObjectLiteralExpression(schemaObject)) return
      for (const property of schemaObject.properties) {
        if (
          ts.isPropertyAssignment(property)
          && staticPropertyName(property) === 'optional'
          && property.initializer.kind === ts.SyntaxKind.TrueKeyword
        ) {
          allowsMissing = true
          return
        }
      }
    }
    ts.forEachChild(node, visit)
  }
  visit(validatorDeclaration)
  return allowsMissing
}

/**
 * Derive channel argument and result types from the main-process handlers.
 *
 * Argument types are the structural return types of the `validate*Payload`
 * functions that guard each channel; result types are the awaited return type
 * of the `ipcMain.handle` callback. Handlers that cannot be reduced to a
 * self-contained type are reported as `null` (rendered as `unknown`).
 *
 * @param {{ handlerFiles: string[] }} options
 * @returns {{
 *   channelArguments: Record<string, { type: string, optional: boolean }>,
 *   channelResults: Record<string, string | null>,
 * }}
 */
export function deriveIpcChannelTypes({ handlerFiles }) {
  const program = ts.createProgram(handlerFiles, {
    allowJs: true,
    checkJs: true,
    target: ts.ScriptTarget.ES2022,
    module: ts.ModuleKind.ESNext,
    moduleResolution: ts.ModuleResolutionKind.Bundler,
    noEmit: true,
    strict: true,
    skipLibCheck: true,
  })
  const checker = program.getTypeChecker()
  const validatorTypes = new Map()
  const validatorAllowsMissing = new Map()

  for (const file of handlerFiles) {
    const sourceFile = program.getSourceFile(file)
    if (!sourceFile) continue
    function visitValidator(node) {
      if (
        ts.isFunctionDeclaration(node)
        && node.name
        && /^validate[A-Z].*Payload$/.test(node.name.text)
      ) {
        const signature = checker.getSignatureFromDeclaration(node)
        const returnType = signature ? checker.getReturnTypeOfSignature(signature) : null
        if (returnType) {
          validatorTypes.set(node.name.text, renderType(checker, returnType, new Set(), node))
          validatorAllowsMissing.set(node.name.text, schemaAllowsMissingPayload(node))
        }
      }
      ts.forEachChild(node, visitValidator)
    }
    visitValidator(sourceFile)
  }

  const channelArguments = {}
  const channelResults = {}

  for (const file of handlerFiles) {
    const sourceFile = program.getSourceFile(file)
    if (!sourceFile) continue
    function visitHandler(node) {
      if (
        ts.isCallExpression(node)
        && ts.isPropertyAccessExpression(node.expression)
        && node.expression.name.text === 'handle'
        && node.expression.expression.getText(sourceFile) === 'ipcMain'
      ) {
        const channel = node.arguments[0] ? literalText(node.arguments[0]) : null
        const callback = node.arguments[1]
        if (channel && callback) {
          const validators = new Set()
          function collectValidators(child) {
            if (
              ts.isCallExpression(child)
              && ts.isIdentifier(child.expression)
              && validatorTypes.has(child.expression.text)
            ) {
              validators.add(child.expression.text)
            }
            ts.forEachChild(child, collectValidators)
          }
          collectValidators(callback)
          if (validators.size === 1) {
            const [validator] = validators
            channelArguments[channel] = {
              type: validatorTypes.get(validator),
              optional: validatorAllowsMissing.get(validator) === true,
            }
          }

          const signature = checker.getSignatureFromDeclaration(callback)
          let returnType = signature ? checker.getReturnTypeOfSignature(signature) : null
          if (returnType && checker.getAwaitedType) {
            returnType = checker.getAwaitedType(returnType)
          }
          const rendered = returnType ? renderType(checker, returnType, new Set(), callback) : null
          channelResults[channel] = rendered && isUsableResultType(rendered) ? rendered : null
        }
      }
      ts.forEachChild(node, visitHandler)
    }
    visitHandler(sourceFile)
  }

  return { channelArguments, channelResults }
}

/**
 * Build per-method argument/result descriptions from the preload surface and
 * the derived channel types.
 *
 * @param {ReturnType<typeof extractDesktopPetBridgeSurface>} surface
 * @param {{ channelArguments: Record<string, { type: string, optional: boolean }>, channelResults: Record<string, string | null> }} channelTypes
 * @returns {Record<string, { argument: string, result: string }>}
 */
export function buildDesktopPetMethodTypes(surface, channelTypes) {
  const methodTypes = {}

  for (const name of Object.keys(surface).sort()) {
    const entry = surface[name]
    let argument = UNKNOWN_TYPE
    const singleCall = entry.calls.length === 1 ? entry.calls[0] : null

    if (entry.params.length === 0) {
      argument = 'readonly []'
    } else if (entry.params.length === 1 && singleCall && singleCall.direct) {
      const channelArgument = channelTypes.channelArguments[singleCall.channel]
      if (
        channelArgument
        && singleCall.argumentCount === 2
        && singleCall.payloadExpression === entry.params[0]
        && isUsableArgumentType(channelArgument.type)
      ) {
        const parameter = entry.params[0]
        argument = channelArgument.optional
          ? `readonly [${parameter}?: ${channelArgument.type}]`
          : `readonly [${parameter}: ${channelArgument.type}]`
      }
    }

    const result = singleCall && entry.params.length <= 1 && singleCall.direct
      ? channelTypes.channelResults[singleCall.channel] ?? UNKNOWN_TYPE
      : UNKNOWN_TYPE

    methodTypes[name] = { argument, result }
  }

  return methodTypes
}

function renderMethodArgumentMap(methodTypes) {
  const names = Object.keys(methodTypes).sort()
  if (names.length === 0) return 'export interface DesktopPetBridgeMethodArguments {}'
  return [
    'export interface DesktopPetBridgeMethodArguments {',
    ...names.map((name) => `  ${propertyKey(name)}: ${methodTypes[name].argument}`),
    '}',
  ].join('\n')
}

function renderMethodResultMap(methodTypes) {
  const names = Object.keys(methodTypes).sort()
  if (names.length === 0) return 'export interface DesktopPetBridgeMethodResults {}'
  return [
    'export interface DesktopPetBridgeMethodResults {',
    ...names.map((name) => `  ${propertyKey(name)}: ${methodTypes[name].result}`),
    '}',
  ].join('\n')
}

function renderGeneratedBridgeInterface(methodTypes) {
  const names = Object.keys(methodTypes)
    .filter((name) => (
      methodTypes[name].argument !== UNKNOWN_TYPE
      && methodTypes[name].result !== UNKNOWN_TYPE
    ))
    .sort()
  if (names.length === 0) return 'export interface DesktopPetGeneratedBridge {}'
  return [
    'export interface DesktopPetGeneratedBridge {',
    ...names.map((name) => (
      `  ${propertyKey(name)}: (...args: DesktopPetBridgeMethodArguments[${quote(name)}]) => Promise<DesktopPetBridgeMethodResults[${quote(name)}]>`
    )),
    '}',
  ].join('\n')
}

/**
 * Render the generated TypeScript module for a bridge surface.
 *
 * @param {ReturnType<typeof extractDesktopPetBridgeSurface>} surface
 * @param {Record<string, { argument: string, result: string }>} [methodTypes]
 * @returns {string}
 */
export function renderDesktopPetBridgeTypes(surface, methodTypes = {}) {
  const names = Object.keys(surface).sort()
  const invokeChannels = new Set()
  const eventChannels = new Set()
  const conditionalKeys = []

  const lines = [HEADER, '', 'export const DESKTOP_PET_BRIDGE_SURFACE = {']
  for (const name of names) {
    const entry = surface[name]
    const invoke = [...new Set(entry.invoke)].sort()
    const events = [...new Set(entry.events)].sort()
    if (entry.conditional) conditionalKeys.push(name)
    for (const channel of invoke) invokeChannels.add(channel)
    for (const channel of events) eventChannels.add(channel)
    lines.push(
      `  ${propertyKey(name)}: { conditional: ${entry.conditional === true}, invoke: [${invoke.map(quote).join(', ')}], events: [${events.map(quote).join(', ')}] },`,
    )
  }
  lines.push('} as const')
  lines.push('')
  lines.push('export type DesktopPetBridgeKey = keyof typeof DESKTOP_PET_BRIDGE_SURFACE')
  lines.push('')
  lines.push(renderUnion('DesktopPetConditionalBridgeKey', conditionalKeys))
  lines.push('')
  lines.push(renderUnion('DesktopPetInvokeChannel', [...invokeChannels].sort()))
  lines.push('')
  lines.push(renderUnion('DesktopPetEventChannel', [...eventChannels].sort()))
  lines.push('')
  lines.push(renderMethodArgumentMap(methodTypes))
  lines.push('')
  lines.push(renderMethodResultMap(methodTypes))
  lines.push('')
  lines.push(renderGeneratedBridgeInterface(methodTypes))
  lines.push('')
  lines.push('export type DesktopPetGeneratedBridgeKey = keyof DesktopPetGeneratedBridge')
  lines.push('')

  return lines.join('\n')
}

/**
 * Normalize CRLF line endings so a Windows checkout (core.autocrlf=true) is
 * still comparable with the LF generator output.
 *
 * @param {string} text
 * @returns {string}
 */
export function normalizeGeneratedTypesLineEndings(text) {
  return text.replace(/\r\n/g, '\n')
}

/**
 * Compare checked-in generator output with freshly rendered output.
 *
 * @param {string} expected freshly rendered text
 * @param {string} actual checked-in text
 * @returns {boolean}
 */
export function isGeneratedTypesCurrent(expected, actual) {
  return normalizeGeneratedTypesLineEndings(actual) === normalizeGeneratedTypesLineEndings(expected)
}

function listIpcHandlerFiles() {
  return readdirSync(IPC_DIR)
    .filter((name) => name.endsWith('.js'))
    .sort()
    .map((name) => join(IPC_DIR, name))
}

/**
 * Generate the bridge module from the repository preload and IPC handlers.
 *
 * @param {{ preloadSource?: string, handlerFiles?: string[] }} [options]
 * @returns {string}
 */
export function generateDesktopPetBridgeTypes(options = {}) {
  const preloadSource = options.preloadSource ?? readFileSync(PRELOAD_PATH, 'utf8')
  const handlerFiles = options.handlerFiles ?? listIpcHandlerFiles()
  const surface = extractDesktopPetBridgeSurface(preloadSource)
  const channelTypes = deriveIpcChannelTypes({ handlerFiles })
  return renderDesktopPetBridgeTypes(surface, buildDesktopPetMethodTypes(surface, channelTypes))
}

function main() {
  const expected = generateDesktopPetBridgeTypes()

  if (process.argv.includes(CHECK_FLAG)) {
    const actual = existsSync(GENERATED_PATH)
      ? readFileSync(GENERATED_PATH, 'utf8')
      : ''
    if (!isGeneratedTypesCurrent(expected, actual)) {
      console.error(STALE_MESSAGE)
      process.exit(1)
    }
    return
  }

  mkdirSync(dirname(GENERATED_PATH), { recursive: true })
  writeFileSync(GENERATED_PATH, expected)
}

const invokedPath = process.argv[1] ? resolve(process.argv[1]) : null
if (invokedPath && resolve(fileURLToPath(import.meta.url)) === invokedPath) {
  main()
}
