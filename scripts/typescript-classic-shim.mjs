/**
 * TypeScript 7 ships a native compiler (bin/tsc) but removed the classic
 * compiler API from the package root export. Ecosystem tools still need the
 * TS 6 API: typescript-eslint, knip, and audit scripts that use
 * createSourceFile / ScriptTarget.
 *
 * This postinstall step keeps `typescript@7` as the installed package (so
 * `tsc` is 7.x) while redirecting `require('typescript')` / `import 'typescript'`
 * to the side-by-side `typescript6` (npm alias of typescript@6) classic API.
 *
 * See: typescript-eslint issue #10940 and the TS 7 side-by-side guidance.
 */
import { existsSync, mkdirSync, readFileSync, symlinkSync, unlinkSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { dirname, join, relative } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const require = createRequire(import.meta.url)

function resolvePackageDir(name) {
  try {
    return dirname(require.resolve(`${name}/package.json`))
  } catch {
    return null
  }
}

const ts7Dir = resolvePackageDir('typescript')
const ts6Dir = resolvePackageDir('typescript6')

if (!ts7Dir || !ts6Dir) {
  console.warn('[typescript-classic-shim] skip: typescript or typescript6 not installed')
  process.exit(0)
}

const ts7PkgPath = join(ts7Dir, 'package.json')
const ts7Pkg = JSON.parse(readFileSync(ts7PkgPath, 'utf8'))
const major = Number(String(ts7Pkg.version || '0').split('.')[0])
if (major < 7) {
  // Classic API is already the root export.
  process.exit(0)
}

const libDir = join(ts7Dir, 'lib')
mkdirSync(libDir, { recursive: true })
const shimPath = join(libDir, 'classic-api-shim.cjs')
const shimSource = `/**
 * Auto-generated by scripts/typescript-classic-shim.mjs — do not edit.
 * Re-exports the classic TypeScript 6 compiler API for tooling.
 */
module.exports = require('typescript6')
`

writeFileSync(shimPath, shimSource)

const exportsMap = {
  ...(ts7Pkg.exports && typeof ts7Pkg.exports === 'object' ? ts7Pkg.exports : {}),
  '.': './lib/classic-api-shim.cjs',
  './package.json': './package.json',
}
ts7Pkg.exports = exportsMap
// Keep bin/tsc on the native 7.x compiler; only the library entry is shimmed.
writeFileSync(ts7PkgPath, `${JSON.stringify(ts7Pkg, null, 2)}\n`)

// Ensure project-local `tsc` resolves to the TypeScript 7 native binary.
// Installing the typescript6 alias can steal node_modules/.bin/tsc.
const binDir = join(root, 'node_modules', '.bin')
const binTsc = join(binDir, 'tsc')
const tscBin = join(ts7Dir, 'bin', 'tsc')
if (existsSync(tscBin)) {
  mkdirSync(binDir, { recursive: true })
  try {
    unlinkSync(binTsc)
  } catch {
    // missing is fine
  }
  try {
    symlinkSync(relative(binDir, tscBin), binTsc)
  } catch (error) {
    // Fall back to a small launcher if symlink is blocked.
    writeFileSync(
      binTsc,
      `#!/usr/bin/env node\nimport ${JSON.stringify(tscBin.startsWith('/') ? tscBin : `../typescript/bin/tsc`)}?\n`,
    )
    console.warn('[typescript-classic-shim] symlink failed, wrote launcher:', error instanceof Error ? error.message : error)
  }
}

// Verify dual stack
const classic = require(shimPath)
if (typeof classic.createSourceFile !== 'function') {
  console.error('[typescript-classic-shim] classic API missing createSourceFile')
  process.exit(1)
}
if (!existsSync(tscBin)) {
  console.error('[typescript-classic-shim] missing native tsc binary')
  process.exit(1)
}

console.log(
  `[typescript-classic-shim] ok — package ${ts7Pkg.version}, classic API ${classic.version}, tsc bin -> ${tscBin}`,
)
