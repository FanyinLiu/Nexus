#!/usr/bin/env node

/**
 * Generates src/i18n/keys.ts from the zh-CN reference locale.
 *
 * zh-CN is the source of truth for the translation key set: every key is a
 * flat dotted literal ('settings.panel': '...') in one of the per-namespace
 * modules under src/i18n/locales/zh-CN/. This script collects those keys,
 * sorts them deterministically, and rewrites src/i18n/keys.ts so the runtime
 * `translationKeys` array can no longer drift from the dictionaries.
 *
 * Usage:
 *   node scripts/gen-i18n-keys.mjs           regenerate src/i18n/keys.ts
 *   node scripts/gen-i18n-keys.mjs --check   fail if src/i18n/keys.ts is stale
 */

import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const SOURCE_DIR = join(ROOT, 'src/i18n/locales/zh-CN')
const TARGET_FILE = join(ROOT, 'src/i18n/keys.ts')
const TARGET_REL = 'src/i18n/keys.ts'

// Keys are flat dotted literals, so only the left-hand side of each entry is
// captured. This mirrors the key half of the entry pattern in i18n-audit.mjs.
const KEY_PATTERN = /^\s*'([^']+)'\s*:/gm

function listSourceFiles() {
  return readdirSync(SOURCE_DIR)
    .filter((name) => name.endsWith('.ts') && name !== 'index.ts')
    .sort()
}

function extractKeys() {
  const keys = []
  for (const name of listSourceFiles()) {
    const text = readFileSync(join(SOURCE_DIR, name), 'utf8')
    for (const match of text.matchAll(KEY_PATTERN)) keys.push(match[1])
  }
  return keys
}

// Default string sort compares UTF-16 code units; the explicit comparator
// keeps that deterministic, environment-independent order obvious.
function compareKeys(left, right) {
  return left < right ? -1 : left > right ? 1 : 0
}

function renderFile(keys) {
  return [
    '// GENERATED by scripts/gen-i18n-keys.mjs — do not edit manually',
    '// Source of truth: the zh-CN reference locale (src/i18n/locales/zh-CN/*.ts).',
    '// After adding or removing locale keys, regenerate with `npm run i18n:gen`;',
    '// `npm run i18n:gen:check` (part of verify:pr) fails while this file is stale.',
    '',
    "import type { TranslationKey } from '../types/i18n.ts'",
    '',
    'export const translationKeys: TranslationKey[] = [',
    ...keys.map((key) => `  '${key}',`),
    ']',
    '',
  ].join('\n')
}

function reportCheckFailure(current, expected) {
  const currentKeys = new Set([...current.matchAll(/^\s*'([^']+)'\s*,/gm)].map((m) => m[1]))
  const expectedKeys = new Set([...expected.matchAll(/^\s*'([^']+)'\s*,/gm)].map((m) => m[1]))
  const stale = [...currentKeys].filter((key) => !expectedKeys.has(key))
  const missing = [...expectedKeys].filter((key) => !currentKeys.has(key))

  console.error(`${TARGET_REL} is out of date.`)
  if (missing.length) console.error(`- keys missing from ${TARGET_REL}: ${missing.sort(compareKeys).join(', ')}`)
  if (stale.length) console.error(`- keys no longer in zh-CN locale: ${stale.sort(compareKeys).join(', ')}`)
  if (!missing.length && !stale.length) {
    console.error('- key sets match but content/ordering differs (file was edited manually?)')
    const currentLines = current.split('\n')
    const expectedLines = expected.split('\n')
    const shown = 5
    let count = 0
    for (let index = 0; index < Math.max(currentLines.length, expectedLines.length) && count < shown; index += 1) {
      if (currentLines[index] !== expectedLines[index]) {
        console.error(`  line ${index + 1}: current ${JSON.stringify(currentLines[index])} expected ${JSON.stringify(expectedLines[index])}`)
        count += 1
      }
    }
  }
  console.error('Run `npm run i18n:gen` to regenerate.')
}

const keys = extractKeys()
const duplicates = keys.filter((key, index) => keys.indexOf(key) !== index)
if (duplicates.length) {
  console.error(`duplicate keys in zh-CN locale: ${[...new Set(duplicates)].join(', ')}`)
  process.exit(1)
}

const sorted = [...keys].sort(compareKeys)
const expected = renderFile(sorted)

if (process.argv.includes('--check')) {
  const current = readFileSync(TARGET_FILE, 'utf8')
  if (current !== expected) {
    reportCheckFailure(current, expected)
    process.exit(1)
  }
  console.log(`${TARGET_REL} is up to date (${sorted.length} keys)`)
} else {
  writeFileSync(TARGET_FILE, expected)
  console.log(`generated ${TARGET_REL}: ${sorted.length} keys from ${listSourceFiles().length} zh-CN modules`)
}
